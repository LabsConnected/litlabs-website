/**
 * Command Center local event log.
 *
 * Authoritative record for Command Center test/diagnostic events.
 * Append-only JSONL on local disk — intentionally NOT a Supabase table.
 *
 * Path resolution:
 *   COMMAND_CENTER_EVENT_LOG_PATH (absolute or cwd-relative)
 *   default: <cwd>/logs/command-center-events.jsonl
 *
 * Node runtime only — never import from edge/client code.
 */

import { mkdirSync, appendFileSync, readFileSync, existsSync } from "fs";
import path from "path";

export interface CommandCenterEvent {
  /** Event family, e.g. "command-center-ping". */
  type: string;
  /** Idempotency key supplied by the caller or generated by the task. */
  idempotencyKey: string;
  /** Lifecycle status of this record. */
  status: "attempt" | "delivered" | "failed" | "deduplicated";
  /** ISO-8601 timestamp written by the logger. */
  loggedAt?: string;
  /** Small structured detail — must never contain secrets. */
  detail?: Record<string, unknown>;
}

export function eventLogPath(): string {
  const configured = process.env.COMMAND_CENTER_EVENT_LOG_PATH;
  return path.resolve(configured ?? path.join("logs", "command-center-events.jsonl"));
}

export function appendLocalEvent(event: CommandCenterEvent): string {
  const file = eventLogPath();
  mkdirSync(path.dirname(file), { recursive: true });
  const record: CommandCenterEvent = {
    ...event,
    loggedAt: new Date().toISOString(),
  };
  appendFileSync(file, JSON.stringify(record) + "\n", "utf8");
  return file;
}

/**
 * True when the log already contains a `delivered` record for this key —
 * used by the ping task to make retries idempotent.
 */
export function hasDeliveredKey(type: string, idempotencyKey: string): boolean {
  const file = eventLogPath();
  if (!existsSync(file)) return false;

  const lines = readFileSync(file, "utf8").split("\n");
  for (const line of lines) {
    if (!line.trim()) continue;
    try {
      const record = JSON.parse(line) as CommandCenterEvent;
      if (
        record.type === type &&
        record.idempotencyKey === idempotencyKey &&
        record.status === "delivered"
      ) {
        return true;
      }
    } catch {
      // Corrupt line — skip, keep scanning.
    }
  }
  return false;
}
