<#
.SYNOPSIS
  Snapshot the installed `litt` launcher shims and generate tested
  install/rollback scripts for the perf-branch release.

.DESCRIPTION
  READ-ONLY with respect to the launcher: copies the three pnpm shims and
  records hashes/paths into a manifest. Generates:

    install-launcher.ps1   — flips the global shim to this build (pnpm link)
    rollback-launcher.ps1  — restores the global shim to litt-runtime

  Neither generated script runs here. Run install only on Larry's approval.

.PARAMETER ReleaseDir
  Output directory for snapshots + generated scripts.
#>
param(
  [string]$ReleaseDir = (Join-Path $PSScriptRoot "..\..\..\.evidence\release-prep-$(Get-Date -Format 'yyyyMMdd-HHmmss')")
)

$ErrorActionPreference = "Stop"
$PnpmDir   = "$env:LOCALAPPDATA\pnpm"
$Shims     = @("litt", "litt.CMD", "litt.ps1")
$PerfPkg   = "C:\LiTT\Worktrees\litt-cli-perf\packages\litt-cli"
$RuntimePkg= "C:\LiTT\Worktrees\litt-runtime\packages\litt-cli"

New-Item -ItemType Directory -Force -Path $ReleaseDir | Out-Null

function Get-Sha256([string]$Path) {
  $line = certutil -hashfile $Path SHA256 | Select-Object -Index 1
  return ($line -replace '\s', '').ToLower()
}

# 1. Snapshot the current shims with hashes
$manifest = [ordered]@{
  capturedAt   = (Get-Date).ToString("o")
  pnpmDir      = $PnpmDir
  perfPackage  = $PerfPkg
  perfSha      = (git -C "C:\LiTT\Worktrees\litt-cli-perf" rev-parse HEAD).Trim()
  runtimePackage = $RuntimePkg
  runtimeSha   = (git -C "C:\LiTT\Worktrees\litt-runtime" rev-parse HEAD).Trim()
  shims        = @()
}
foreach ($s in $Shims) {
  $p = Join-Path $PnpmDir $s
  if (Test-Path $p) {
    Copy-Item $p (Join-Path $ReleaseDir "$s.orig")
    $manifest.shims += [ordered]@{
      name   = $s
      sha256 = (Get-Sha256 $p)
      bytes  = (Get-Item $p).Length
      snapshot = "$s.orig"
    }
  }
}

# 2. Record the runtime dist the launcher currently executes (rollback target)
$rtDist = Join-Path $RuntimePkg "dist\index.js"
$perfDist = Join-Path $PerfPkg "dist\index.js"
$manifest.runtimeDistSha256 = (Get-Sha256 $rtDist)
$manifest.perfDistSha256    = (Get-Sha256 $perfDist)
$manifest.perfBuildMeta     = [System.IO.File]::ReadAllText((Join-Path $PerfPkg "dist\.build-meta.json"))

# 3. install-launcher.ps1 — repoints the global shim at the perf build
@'
# install-launcher.ps1 — point global `litt` at the perf worktree build.
# Generated by prepare-release.ps1. Run only with Larry's approval.
$ErrorActionPreference = "Stop"
$PerfPkg = "C:\LiTT\Worktrees\litt-cli-perf\packages\litt-cli"
Write-Host "[install] pnpm link --global from $PerfPkg"
Push-Location $PerfPkg
try { pnpm link --global } finally { Pop-Location }
$shim = Get-Content "$env:LOCALAPPDATA\pnpm\litt.CMD" -Raw
if ($shim -notmatch "litt-cli-perf") { throw "Shim does not point at litt-cli-perf — aborting" }
litt --version
Write-Host "[install] OK — litt now resolves to the perf build. Roll back with rollback-launcher.ps1"
'@ | Set-Content (Join-Path $ReleaseDir "install-launcher.ps1") -Encoding UTF8

# 4. rollback-launcher.ps1 — restores the global shim to litt-runtime
@'
# rollback-launcher.ps1 — point global `litt` back at the litt-runtime build.
# Generated by prepare-release.ps1. Safe to run at any time.
$ErrorActionPreference = "Stop"
$RuntimePkg = "C:\LiTT\Worktrees\litt-runtime\packages\litt-cli"
Write-Host "[rollback] pnpm link --global from $RuntimePkg"
Push-Location $RuntimePkg
try { pnpm link --global } finally { Pop-Location }
$shim = Get-Content "$env:LOCALAPPDATA\pnpm\litt.CMD" -Raw
if ($shim -notmatch "litt-runtime") { throw "Shim does not point at litt-runtime — aborting" }
litt --version
Write-Host "[rollback] OK — litt restored to litt-runtime (pre-release state)."
'@ | Set-Content (Join-Path $ReleaseDir "rollback-launcher.ps1") -Encoding UTF8

$manifest | ConvertTo-Json -Depth 5 | Set-Content (Join-Path $ReleaseDir "manifest.json") -Encoding UTF8
Write-Host "[prepare] Release prep complete → $ReleaseDir"
Get-ChildItem $ReleaseDir | Select-Object Name, Length | Format-Table -AutoSize
